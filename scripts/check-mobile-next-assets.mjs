#!/usr/bin/env node
// The /m-next client is a directory of plain files the hub compiles in
// (services/hub-rs/assets/web/m-next). Two lists must name exactly those
// files, and both are generated here so a new module cannot be forgotten:
//
//   services/hub-rs/src/server/m_next_assets.rs  the include_bytes! table the
//                                                hub serves /m-next/* from
//   assets/web/m-next/sw.js                      the service worker's precache
//                                                list and versioned cache name
//                                                (a content hash, so any asset
//                                                change ships a new shell)
//
// It also parses every module as ESM and checks each relative import names a
// file that exists, which is the whole of what a bundler would have caught.
//
//   node scripts/check-mobile-next-assets.mjs           check (CI, make check-hub-rust-assets)
//   node scripts/check-mobile-next-assets.mjs --write   regenerate both lists
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'services/hub-rs/assets/web/m-next');
const TABLE = path.join(ROOT, 'services/hub-rs/src/server/m_next_assets.rs');
const SW = path.join(DIR, 'sw.js');
const write = process.argv.includes('--write');

function walk(dir, prefix = '') {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name.endsWith('.md')) continue;
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...walk(path.join(dir, entry.name), rel));
    else out.push(rel);
  }
  return out.sort();
}

const files = walk(DIR);
const problems = [];

// ── the Rust table ────────────────────────────────────────────────────────
const table =
  '//! GENERATED by scripts/check-mobile-next-assets.mjs --write. Do not edit.\n' +
  '//! Every file under assets/web/m-next, served by `web::m_next`.\n' +
  'pub(super) const ASSETS: &[(&str, &[u8])] = &[\n' +
  files
    .map((f) => {
      // rustfmt's layout, so `cargo fmt --check` agrees with the generator.
      // (A tuple stays on one line while its contents fit fn_call_width, 60.)
      const inner = `${JSON.stringify(f)}, include_bytes!("../../assets/web/m-next/${f}")`;
      return inner.length <= 60
        ? `    (${inner}),\n`
        : `    (\n        ${JSON.stringify(f)},\n        include_bytes!("../../assets/web/m-next/${f}"),\n    ),\n`;
    })
    .join('') +
  '];\n';

// ── the service worker's precache list ───────────────────────────────────
// Everything but the worker itself; the navigation entry is the scope root.
const shell = ['./', ...files.filter((f) => f !== 'sw.js' && f !== 'index.html')];
const hash = crypto.createHash('sha256');
for (const f of files) if (f !== 'sw.js') hash.update(f).update(fs.readFileSync(path.join(DIR, f)));
const version = hash.digest('hex').slice(0, 12);
const swText = fs.readFileSync(SW, 'utf8');
const begin = '// <generated-shell>';
const end = '// </generated-shell>';
const a = swText.indexOf(begin), b = swText.indexOf(end);
if (a < 0 || b < a) {
  problems.push('sw.js lost its generated-shell markers');
}
const region =
  `${begin}\nconst CACHE = 'wks-m-next-${version}';\nconst SHELL = [\n` +
  shell.map((f) => `  ${JSON.stringify(f)},\n`).join('') +
  `];\n`;
const nextSw = a >= 0 && b > a ? swText.slice(0, a) + region + swText.slice(b) : swText;

if (write) {
  fs.writeFileSync(TABLE, table);
  fs.writeFileSync(SW, nextSw);
} else {
  const current = fs.existsSync(TABLE) ? fs.readFileSync(TABLE, 'utf8') : '';
  if (current !== table) problems.push('services/hub-rs/src/server/m_next_assets.rs is stale');
  if (nextSw !== swText) problems.push('assets/web/m-next/sw.js precache list is stale');
}

// ── modules parse, and their relative imports exist ──────────────────────
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'wks-m-next-check-'));
try {
  for (const f of files.filter((f) => f.endsWith('.js'))) {
    const src = fs.readFileSync(path.join(DIR, f), 'utf8');
    const probe = path.join(tmp, f.replace(/[\\/]/g, '__') + '.mjs');
    fs.writeFileSync(probe, f === 'sw.js' ? src : src);
    const parsed = spawnSync(process.execPath, ['--check', probe], { encoding: 'utf8' });
    if (parsed.status !== 0) problems.push(`${f} does not parse:\n${parsed.stderr}`);
    for (const m of src.matchAll(/(?:^|\n)\s*(?:import|export)\s[^'"]*?from\s*['"](\.[^'"]+)['"]/g)) {
      const target = path.normalize(path.join(path.dirname(f), m[1]));
      if (!files.includes(target.split(path.sep).join('/'))) problems.push(`${f} imports missing ${m[1]}`);
    }
  }
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}

// ── index.html references exist ──────────────────────────────────────────
const index = fs.readFileSync(path.join(DIR, 'index.html'), 'utf8');
for (const m of index.matchAll(/(?:href|src)="(\.\/[^"#?]+)"/g)) {
  if (!files.includes(m[1].slice(2))) problems.push(`index.html references missing ${m[1]}`);
}

if (problems.length) {
  console.error('check-mobile-next-assets:\n  ' + problems.join('\n  '));
  if (!write) console.error('  run: node scripts/check-mobile-next-assets.mjs --write');
  process.exit(1);
}
console.log(`check-mobile-next-assets: ${files.length} files, shell ${version}${write ? ' (written)' : ''}`);
