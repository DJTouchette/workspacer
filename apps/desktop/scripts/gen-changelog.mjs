// Generates apps/desktop/src/renderer/src/lib/changelog.generated.ts from the
// repo's CHANGELOG.md.
//
// CHANGELOG.md is the SINGLE SOURCE for release notes. It is hand-written (the
// entries say what changed and why, which no commit-subject scraper produces),
// and everything else derives from it:
//
//   - this generated module, which the app renders in Settings → Updates and in
//     the "what's new" notice after an update;
//   - the GitHub Release body, extracted at tag time by release.yml.
//
// Generated rather than read at runtime so the notes work offline, in a packaged
// build, and in the web/remote renderer — none of which can read the repo. Same
// seam and same reasoning as configDefaults.generated.ts.
//
// Run: npm run gen:changelog  (wired into prebuild:main).
// A drift test (changelog.test.ts) fails if the committed .ts falls out of sync
// with the markdown, so a stale checkout is caught even without a rebuild.

import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath, pathToFileURL } from 'url';
import { dirname, join } from 'path';
import prettier from 'prettier';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..', '..');
const SOURCE = join(repoRoot, 'CHANGELOG.md');
const OUT = join(here, '..', 'src', 'renderer', 'src', 'lib', 'changelog.generated.ts');

/**
 * Parse the Keep-a-Changelog subset this file actually uses:
 *
 *   ## [1.2.3] - 2026-07-29     a release heading (or ## [Unreleased])
 *   ### Added                   a section
 *   - an entry, which may wrap
 *     onto indented continuation lines
 *
 * Anything else (the file's prose header, link definitions) is ignored rather
 * than guessed at. An entry keeps its inline markdown verbatim — the renderer
 * has a markdown component, so **bold** and `code` survive to the UI.
 */
export function parseChangelog(markdown) {
  const releases = [];
  let release = null;
  let section = null;

  const pushItem = (text) => {
    if (!release || !section) return;
    section.items.push(text.trim());
  };

  for (const rawLine of markdown.split('\n')) {
    const line = rawLine.replace(/\s+$/, '');

    const head = /^##\s+\[([^\]]+)\](?:\s*-\s*(\S+))?/.exec(line);
    if (head) {
      const version = head[1];
      const unreleased = version.toLowerCase() === 'unreleased';
      release = {
        version: unreleased ? 'Unreleased' : version,
        date: head[2] ?? '',
        unreleased,
        sections: [],
      };
      releases.push(release);
      section = null;
      continue;
    }

    const sec = /^###\s+(.+)$/.exec(line);
    if (sec && release) {
      section = { title: sec[1].trim(), items: [] };
      release.sections.push(section);
      continue;
    }

    const item = /^-\s+(.*)$/.exec(line);
    if (item) {
      pushItem(item[1]);
      continue;
    }

    // A continuation line: indented, non-empty, and only meaningful while an
    // entry is open. Joined with a space so the entry is one paragraph again —
    // the hard wrapping in the file is for reading the diff, not for the UI.
    if (/^\s{2,}\S/.test(line) && section && section.items.length > 0) {
      section.items[section.items.length - 1] += ' ' + line.trim();
    }
  }

  // A release heading with no entries under it is almost always a typo'd section
  // marker, and it would render as an empty card. Surface it rather than ship it.
  for (const r of releases) {
    const count = r.sections.reduce((n, s) => n + s.items.length, 0);
    if (count === 0) {
      throw new Error(
        `CHANGELOG.md: "${r.version}" has no entries — a release heading with nothing under it ` +
          `renders as an empty card in the app and an empty GitHub release body.`,
      );
    }
  }
  return releases;
}

// Everything below is the GENERATOR. It runs only when this file is executed
// directly — changelog.test.ts imports parseChangelog from here so the drift
// guard checks the real parser rather than a copy of it, and importing a module
// must not write files.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}

async function main() {
  const releases = parseChangelog(readFileSync(SOURCE, 'utf8'));

  const banner = `// GENERATED by apps/desktop/scripts/gen-changelog.mjs — DO NOT EDIT.
  //
  // Source: CHANGELOG.md at the repo root. Edit that, then run
  // \`npm run gen:changelog\` (or any build, which runs it via prebuild:main).
  // changelog.test.ts fails when this file and the markdown disagree.

  /** One "### Added" / "### Fixed" block under a release. */
  export interface ChangelogSection {
    title: string;
    /** Entries with their inline markdown intact, one paragraph each. */
    items: string[];
  }

  export interface ChangelogRelease {
    /** "1.2.3", or "Unreleased" for the in-progress section. */
    version: string;
    /** ISO date from the heading; empty for Unreleased. */
    date: string;
    unreleased: boolean;
    sections: ChangelogSection[];
  }

  /** Newest first, exactly as CHANGELOG.md orders them. */
  export const CHANGELOG: readonly ChangelogRelease[] = ${JSON.stringify(releases, null, 2)};
  `;

  const formatted = await prettier.format(banner, {
    ...(await prettier.resolveConfig(OUT)),
    parser: 'typescript',
  });
  writeFileSync(OUT, formatted);
  console.log(
    `changelog.generated.ts: ${releases.length} release(s), ` +
      `${releases.reduce((n, r) => n + r.sections.reduce((m, s) => m + s.items.length, 0), 0)} entries`,
  );
}
