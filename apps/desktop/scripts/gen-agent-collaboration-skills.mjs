// Bundle app-owned ordinary-agent skills into main's normal tsc distribution.
// Installed apps must never depend on source-tree asset paths at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const desktop = fileURLToPath(new URL('../', import.meta.url));
const files = {};
for (const name of ['project-brief', 'spawn-agent']) {
  files[`${name}/SKILL.md`] = readFileSync(
    resolve(desktop, 'assets/skills', name, 'SKILL.md'),
    'utf8',
  );
}
writeFileSync(
  resolve(desktop, 'src/main/services/agentCollaborationSkills.generated.json'),
  `${JSON.stringify(files, null, 2)}\n`,
);

// Headless uses the same immutable, pointer-only installation contract as the
// desktop. Generate both bodies and the exact desktop version hash from the
// same ordered object so neither runtime can drift.
const version = createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0, 16);
const goFiles = Object.entries(files)
  .map(([name, body]) => `\t${JSON.stringify(name)}: ${JSON.stringify(body)},`)
  .join('\n');
writeFileSync(
  resolve(desktop, '../../services/hub/cmd/brain/agent_collaboration_skills_generated.go'),
  `// Code generated by apps/desktop/scripts/gen-agent-collaboration-skills.mjs; DO NOT EDIT.\n` +
    `package main\n\n` +
    `const headlessAgentCollaborationSkillsVersion = ${JSON.stringify(version)}\n\n` +
    `var headlessAgentCollaborationSkillFiles = map[string]string{\n${goFiles}\n}\n`,
);
