#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
const desktop = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.resolve(desktop, '../..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'contracts/desktop-service-methods.json'), 'utf8'));
for (const names of [manifest.ownerMethods, manifest.assetMethods]) {
  if (!Array.isArray(names) || new Set(names).size !== names.length || names.some((name) => typeof name !== 'string' || !/^[a-z][A-Za-z0-9.]+$/.test(name))) throw new Error('Invalid desktop service method manifest');
}
if (manifest.ownerMethods.some((name) => !name.startsWith('desktop.'))) throw new Error('Owner methods must use the protected desktop namespace');
function write(file, content) { if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) fs.writeFileSync(file, content); }
const generatedFile = path.join(desktop, 'src/main/shared/desktopServices.generated.ts');
const generatedSource = '// Generated by scripts/gen-desktop-services.mjs; edit contracts/desktop-service-methods.json.\nconst methods = ' + JSON.stringify({ownerMethods:manifest.ownerMethods,assetMethods:manifest.assetMethods}, null, 2) + ' as const;\nexport default methods;\n';
write(generatedFile, await format(generatedSource, { ...await resolveConfig(generatedFile), filepath: generatedFile }));
