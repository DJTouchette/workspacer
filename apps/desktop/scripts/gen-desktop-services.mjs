#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const desktop = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.resolve(desktop, '../..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'contracts/desktop-service-methods.json'), 'utf8'));
for (const names of [manifest.ownerMethods, manifest.assetMethods]) {
  if (!Array.isArray(names) || new Set(names).size !== names.length || names.some((name) => typeof name !== 'string' || !/^[a-z][A-Za-z0-9.]+$/.test(name))) throw new Error('Invalid desktop service method manifest');
}
if (manifest.ownerMethods.some((name) => !name.startsWith('desktop.'))) throw new Error('Owner methods must use the protected desktop namespace');
function write(file, content) { if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) fs.writeFileSync(file, content); }
write(path.join(desktop, 'src/main/shared/desktopServices.generated.ts'),
  '// Generated by scripts/gen-desktop-services.mjs; edit contracts/desktop-service-methods.json.\nconst methods = ' + JSON.stringify({ownerMethods:manifest.ownerMethods,assetMethods:manifest.assetMethods}, null, 2) + ' as const;\nexport default methods;\n');
const policyFile = path.join(root, 'services/hub/internal/capspec/desktop.go');
let policy = fs.readFileSync(policyFile, 'utf8');
for (const [symbol, names] of [['DesktopServices', manifest.ownerMethods], ['UIAssetServices', manifest.assetMethods]]) {
  const pattern = new RegExp(`var ${symbol} = \\[\\]string\\{[\\s\\S]*?\\}`);
  if (!pattern.test(policy)) throw new Error(`Missing ${symbol} registry`);
  policy = policy.replace(pattern, `var ${symbol} = []string{\n${names.map((name) => '\t' + JSON.stringify(name) + ',').join('\n')}\n}`);
}
write(policyFile, policy);
const gateFile = path.join(root, 'services/hub/internal/bus/desktop.go');
const gate = fs.readFileSync(gateFile, 'utf8');
const pattern = /func desktopServiceAllowed\(method string, cn \*conn\) bool \{[\s\S]*?\n\}/;
if (!pattern.test(gate)) throw new Error('Missing desktop owner gate');
write(gateFile, gate.replace(pattern,
  'func desktopServiceAllowed(method string, cn *conn) bool {\n\tswitch method {\n' +
  manifest.ownerMethods.map((name) => `\tcase ${JSON.stringify(name)}:\n\t\treturn authenticatedDesktopUser(${JSON.stringify(name)}, cn)`).join('\n') +
  '\n\tdefault:\n\t\treturn false\n\t}\n}'));
